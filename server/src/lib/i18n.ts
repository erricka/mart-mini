export type Lang = 'km' | 'en';
const als = new AsyncLocalStorage<Lang>();

export const runWithLang = <T>(lang: Lang, fn: () => T) => als.run(lang, fn);
export const currentLang = (): Lang => als.getStore() ?? config.DEFAULT_LANGUAGE;
export const parseLang = (v: unknown): Lang | null => (v === 'km' || v === 'en' ? v : null);
/** Shop data with an optional English version: English customers see it when it exists. */
export const pick = (primary: string, english?: string | null, lang: Lang = currentLang()) => (lang === 'en' && english?.trim() ? english : primary);

export const userLang = (u: { languageCode?: string | null } | null | undefined): Lang => parseLang(u?.languageCode) ?? config.DEFAULT_LANGUAGE;

