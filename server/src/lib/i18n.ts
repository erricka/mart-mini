const dict: Record<Lang, Record<Key, string>> = { en, km };

export const isKey = (k: string): k is Key => k in en;

/** Translate `key` into `lang` (default: the current request's language), filling {placeholders}. */
export function tr(key: Key, vars: Record<string, string | number> = {}, lang: Lang = currentLang()): string {
  const template = dict[lang][key] ?? en[key];
  return template.replace(/\{(\w+)\}/g, (_, k: string) => (k in vars ? String(vars[k]) : `{${k}}`));
}
